import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { generateDeliveryTypes, type ModuleManifest } from '@litljomi/cms-schema';

const HEADER = '// Generated by tools/cli (gen-types). Do not edit.\n';
const MODULE_NAME = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/;
const USAGE = 'usage: gen-types --module <name> --out <file>';

export interface CliIo {
  log: (line: string) => void;
  error?: (line: string) => void;
}

/** The delivered-shape declarations of a module's types, with the generated-file header. */
export function renderTypes(manifest: ModuleManifest): string {
  return HEADER + '\n' + generateDeliveryTypes(manifest.types).trimEnd() + '\n';
}

function flag(args: string[], name: string): string | undefined {
  const i = args.indexOf(name);
  const value = i === -1 ? undefined : args[i + 1];
  return value === undefined || value.startsWith('--') ? undefined : value;
}

async function loadModule(name: string): Promise<ModuleManifest> {
  // The CLI is the one place besides the registry that names modules; the name is validated above.
  const loaded = (await import(`@litljomi/module-${name}`)) as { default?: ModuleManifest };
  if (loaded.default === undefined) throw new Error(`module ${name} has no default export`);
  return loaded.default;
}

/** Runs one command; returns the exit code (0 ok, 1 failure, 2 usage). */
export async function runCli(args: string[], io: CliIo): Promise<number> {
  const error = io.error ?? io.log;
  const [command, ...rest] = args;
  if (command !== 'gen-types') {
    error(USAGE);
    return 2;
  }
  const name = flag(rest, '--module');
  const out = flag(rest, '--out');
  if (name === undefined || out === undefined || !MODULE_NAME.test(name)) {
    error(USAGE);
    return 2;
  }
  let manifest: ModuleManifest;
  try {
    manifest = await loadModule(name);
  } catch (e) {
    error(`cannot load module "${name}": ${e instanceof Error ? e.message : String(e)}`);
    return 1;
  }
  const file = resolve(out);
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, renderTypes(manifest));
  io.log(`wrote ${file}`);
  return 0;
}
