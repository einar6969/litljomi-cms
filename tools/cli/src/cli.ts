import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { generateDeliveryTypes, type ModuleManifest } from '@litljomi/cms-schema';
import { CHECK_SCHEMA_USAGE, runCheckSchema, type CheckSchemaDeps } from './check-schema.ts';
import { BOUNDARY_CHECK_USAGE, runBoundaryCheck, type BoundaryCheckDeps } from './boundary-check.ts';
import { IMPORT_USAGE, runImport, type ImportDeps } from './import.ts';
import { MIGRATE_DRAFTS_USAGE, runMigrateDrafts, type MigrateDraftsDeps } from './migrate-drafts.ts';
import { PROVISION_USAGE, runProvision, type ProvisionDeps } from './provision.ts';

const HEADER = '// Generated by tools/cli (gen-types). Do not edit.\n';
const MODULE_NAME = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/;
const USAGE = [
  'usage: gen-types --module <name> --out <file>',
  PROVISION_USAGE.replace(/^usage: /, '       '),
  BOUNDARY_CHECK_USAGE.replace(/^usage: /, '       '),
  MIGRATE_DRAFTS_USAGE.replace(/^usage: /, '       '),
  CHECK_SCHEMA_USAGE.replace(/^usage: /, '       '),
  IMPORT_USAGE.replace(/^usage: /, '       '),
].join('\n');

export interface CliIo {
  log: (line: string) => void;
  error?: (line: string) => void;
  /** The network, env-file and stdin access of `provision`; main.ts passes Node's, tests inject fakes. */
  provision?: ProvisionDeps;
  /** The network and env-file access of `boundary-check`; main.ts passes Node's, tests inject fakes. */
  boundaryCheck?: BoundaryCheckDeps;
  /** The network and env-file access of `migrate-drafts`; main.ts passes Node's, tests inject fakes. */
  migrateDrafts?: Omit<MigrateDraftsDeps, 'loadModule'>;
  /** The modules/ folder access of `check-schema`; main.ts passes Node's, tests inject fakes. */
  checkSchema?: Omit<CheckSchemaDeps, 'loadModule'>;
  /** The network, file, clock and password access of `import`; main.ts passes Node's, tests inject fakes. */
  import?: Omit<ImportDeps, 'loadModule'>;
}

/** The delivered-shape declarations of a module's types, with the generated-file header. */
export function renderTypes(manifest: ModuleManifest): string {
  return HEADER + '\n' + generateDeliveryTypes(manifest.types).trimEnd() + '\n';
}

function flag(args: string[], name: string): string | undefined {
  const i = args.indexOf(name);
  const value = i === -1 ? undefined : args[i + 1];
  return value === undefined || value.startsWith('--') ? undefined : value;
}

async function loadModule(name: string): Promise<ModuleManifest> {
  // The CLI is the one place besides the registry that names modules; the name is validated above.
  const loaded = (await import(`@litljomi/module-${name}`)) as { default?: ModuleManifest };
  if (loaded.default === undefined) throw new Error(`module ${name} has no default export`);
  return loaded.default;
}

/** Runs one command; returns the exit code (0 ok, 1 failure, 2 usage). */
export async function runCli(args: string[], io: CliIo): Promise<number> {
  const error = io.error ?? io.log;
  const [command, ...rest] = args;
  if (command === 'provision') {
    if (io.provision === undefined) {
      error('provision: no network, file or stdin access was given (run it through main.ts)');
      return 1;
    }
    return runProvision(rest, { log: io.log, error }, io.provision);
  }
  if (command === 'boundary-check') {
    if (io.boundaryCheck === undefined) {
      error('boundary-check: no network or file access was given (run it through main.ts)');
      return 1;
    }
    return runBoundaryCheck(rest, { log: io.log, error }, io.boundaryCheck);
  }
  if (command === 'migrate-drafts') {
    if (io.migrateDrafts === undefined) {
      error('migrate-drafts: no network or file access was given (run it through main.ts)');
      return 1;
    }
    return runMigrateDrafts(rest, { log: io.log, error }, { ...io.migrateDrafts, loadModule });
  }
  if (command === 'check-schema') {
    if (io.checkSchema === undefined) {
      error('check-schema: no file access was given (run it through main.ts)');
      return 1;
    }
    return runCheckSchema(rest, { log: io.log, error }, { ...io.checkSchema, loadModule });
  }
  if (command === 'import') {
    if (io.import === undefined) {
      error('import: no network, file or password access was given (run it through main.ts)');
      return 1;
    }
    return runImport(rest, { log: io.log, error }, { ...io.import, loadModule });
  }
  if (command !== 'gen-types') {
    error(USAGE);
    return 2;
  }
  const name = flag(rest, '--module');
  const out = flag(rest, '--out');
  if (name === undefined || out === undefined || !MODULE_NAME.test(name)) {
    error(USAGE);
    return 2;
  }
  let manifest: ModuleManifest;
  try {
    manifest = await loadModule(name);
  } catch (e) {
    error(`cannot load module "${name}": ${e instanceof Error ? e.message : String(e)}`);
    return 1;
  }
  // `--out` is resolved against the current directory: under `pnpm --filter @litljomi/cli` that is
  // tools/cli, so a path given from another package (apps/demo-site's gen:types) starts with `../../`.
  const file = resolve(out);
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, renderTypes(manifest));
  io.log(`wrote ${file}`);
  return 0;
}
