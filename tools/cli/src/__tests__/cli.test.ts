import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterEach, describe, expect, it } from 'vitest';
import demo from '@litljomi/module-demo';
import { renderTypes, runCli } from '../cli.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', '..');
const dirs: string[] = [];
const tmp = () => {
  const d = mkdtempSync(join(tmpdir(), 'cli-'));
  dirs.push(d);
  return d;
};
afterEach(() => {
  for (const d of dirs.splice(0)) rmSync(d, { recursive: true, force: true });
});

describe('renderTypes', () => {
  it('starts with a generated-file header and declares one interface per type', () => {
    const out = renderTypes(demo);
    expect(out.startsWith('// Generated by tools/cli (gen-types). Do not edit.')).toBe(true);
    expect(out).toContain('export interface EventEntry {');
    expect(out).toContain('startDate: string | null;');
    expect(out.endsWith('\n')).toBe(true);
  });
});

describe('runCli gen-types', () => {
  it('writes the module types to --out, creating directories', async () => {
    const out = join(tmp(), 'a', 'cms.ts');
    const lines: string[] = [];
    const code = await runCli(['gen-types', '--module', 'demo', '--out', out], { log: (l) => lines.push(l) });
    expect(code).toBe(0);
    expect(readFileSync(out, 'utf8')).toBe(renderTypes(demo));
    expect(lines.join('\n')).toContain(out);
  });
  it('fails with usage on an unknown command, a missing flag or a bad module name', async () => {
    const errors: string[] = [];
    const io = { log: () => {}, error: (l: string) => errors.push(l) };
    expect(await runCli([], io)).toBe(2);
    expect(await runCli(['nope'], io)).toBe(2);
    expect(await runCli(['gen-types', '--module', 'demo'], io)).toBe(2);
    expect(await runCli(['gen-types', '--out', 'x.ts'], io)).toBe(2);
    expect(await runCli(['gen-types', '--module', '../evil', '--out', 'x.ts'], io)).toBe(2);
    expect(errors.length).toBe(5);
  });
  it('reports a module that does not exist', async () => {
    const errors: string[] = [];
    const code = await runCli(['gen-types', '--module', 'nosuchmodule', '--out', join(tmp(), 'x.ts')], { log: () => {}, error: (l) => errors.push(l) });
    expect(code).toBe(1);
    expect(errors.join('\n')).toContain('nosuchmodule');
  });
});

describe('the demo site types', () => {
  it('are up to date with the demo module (run `pnpm --filter demo-site gen:types`)', () => {
    const committed = readFileSync(join(root, 'apps', 'demo-site', 'src', 'types', 'cms.ts'), 'utf8');
    expect(committed).toBe(renderTypes(demo));
  });
});
