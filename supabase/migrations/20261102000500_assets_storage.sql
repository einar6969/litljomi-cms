-- Assets, storage buckets and storage policies (spec §4.1 rules 3 and 6, §4.3,
-- §4.5, §5.6, §8.1; plan Task 8, decision 11).
--
-- assets is a tenant table (§4.3): tenant_id not null, and the references to it
-- from draft_refs and revision_refs (deferred from Task 7) are composite with
-- tenant_id, so a document cannot reference another tenant's asset (§4.1
-- rule 3). Grants are exactly those in §4.5, per column where it says so;
-- nothing for anon. RLS with the tenant membership policy for each command
-- granted to authenticated; no platform-admin clause on a content table (§4.5).
-- No SECURITY DEFINER anywhere: the actor triggers are Task 6's invoker
-- functions in private.

-- id is generated by the uploading client and is also the second folder of the
-- storage path (§4.3, §5.6). The path rule mirrors register_asset's (§4.6): an
-- original lives at {tenant_id}/{asset_id}/{filename}, with the tenant id in its
-- canonical lowercase text form, as in the storage policy below. Accepted
-- uploads: JPEG, PNG, WebP; at most 20 MB (§5.6). Not hard-deleted in v1 (§4.3):
-- no DELETE grant for any API role.
create table cms.assets (
  id uuid primary key,
  tenant_id uuid not null references cms.tenants (id),
  original_path text not null,
  filename text not null,
  mime text not null check (mime in ('image/jpeg', 'image/png', 'image/webp')),
  bytes bigint not null check (bytes > 0 and bytes <= 20971520),
  width int not null,
  height int not null,
  sha256 text not null check (sha256 ~ '^[0-9a-f]{64}$'),
  focal_x real check (focal_x between 0 and 1),
  focal_y real check (focal_y between 0 and 1),
  default_alt text,
  public_path text,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid(),
  archived_at timestamptz,
  -- Target of the composite foreign keys from draft_refs and revision_refs.
  unique (tenant_id, id),
  check (original_path like tenant_id::text || '/' || id::text || '/%')
);

-- The deferred foreign keys of Task 7 (plan Task 7 Step 3): the same shape as
-- those refs tables' entry targets. revision_refs restricts deletion.
alter table cms.draft_refs
  add constraint draft_refs_tenant_id_target_asset_id_fkey
  foreign key (tenant_id, target_asset_id) references cms.assets (tenant_id, id);
alter table cms.revision_refs
  add constraint revision_refs_tenant_id_target_asset_id_fkey
  foreign key (tenant_id, target_asset_id) references cms.assets (tenant_id, id) on delete restrict;

-- Actor column cannot be spoofed (decision 11): force_actor rewrites created_by
-- with auth.uid() whenever it is not null; check_actor refuses a final row
-- where a later BEFORE trigger changed it. created_by is not updatable by any
-- API role, so insert only (as entries.created_by).
create trigger assets_force_actor
  before insert on cms.assets
  for each row
  execute function private.force_actor('created_by');

create trigger assets_check_actor
  after insert on cms.assets
  for each row
  execute function private.check_actor('created_by');

-- RLS (§4.5): access requires a membership in the row's tenant. The subquery runs
-- under the memberships policy, which permits the user's own rows.
-- Keep every membership predicate below identical (and identical to those of the
-- other tenant tables): a change to one copy is a change to tenant isolation.
alter table cms.assets enable row level security;

create policy assets_select_member on cms.assets
  for select to authenticated
  using (exists (
    select 1 from cms.memberships m
    where m.tenant_id = assets.tenant_id and m.user_id = (select auth.uid())
  ));

create policy assets_insert_member on cms.assets
  for insert to authenticated
  with check (exists (
    select 1 from cms.memberships m
    where m.tenant_id = assets.tenant_id and m.user_id = (select auth.uid())
  ));

create policy assets_update_member on cms.assets
  for update to authenticated
  using (exists (
    select 1 from cms.memberships m
    where m.tenant_id = assets.tenant_id and m.user_id = (select auth.uid())
  ))
  with check (exists (
    select 1 from cms.memberships m
    where m.tenant_id = assets.tenant_id and m.user_id = (select auth.uid())
  ));

-- Grants (§4.5). authenticated: INSERT and UPDATE per column, so editors never
-- set public_path (worker-owned). service_role (the worker): reads assets and
-- sets public_path when it publishes media (§5.6). anon: none.
grant select on cms.assets to authenticated;
grant insert (id, tenant_id, original_path, filename, mime, bytes, width, height, sha256, default_alt, created_by)
  on cms.assets to authenticated;
grant update (focal_x, focal_y, default_alt, archived_at) on cms.assets to authenticated;
grant select on cms.assets to service_role;
grant update (public_path) on cms.assets to service_role;

-- Buckets (§5.6).
--   media-private  private; editors upload originals at {tenant_id}/{asset_id}/{filename}
--   media-public   public read; the worker copies published media to {tenant_slug}/...
--   delivery       public read; the worker writes release bundles and pointers
-- media-private also carries §5.6's upload limits (20 MB; JPEG, PNG, WebP),
-- which the Storage API enforces on upload; the asset row's constraints above
-- are the database's own check.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values
  ('media-private', 'media-private', false, 20971520, array['image/jpeg', 'image/png', 'image/webp']),
  ('media-public', 'media-public', true, null, null),
  ('delivery', 'delivery', true, null, null);

-- Storage policies (§5.6, §8.1). Editors (authenticated) may select and insert
-- in media-private where the first folder of the object name is a tenant they
-- are a member of; no update or delete. No policy at all for media-public or
-- delivery, nor for anon: only the worker (service_role, which bypasses RLS)
-- writes there, and public reads come from the buckets' public flag.
--
-- The first folder is compared with the tenant id's canonical text form
-- (m.tenant_id::text) instead of being cast with ::uuid as the plan writes it.
-- It is the same membership rule, but a ::uuid cast inside a policy could raise
-- 22P02 on a folder name that is not a UUID, such as media-public's
-- {tenant_slug}/... objects in another bucket or a malformed upload, and make
-- an editor's read of storage.objects fail. The text form never raises, and the
-- prefix must be exactly the lowercase form assets.original_path requires.
-- Keep the membership predicate identical in both policies.
create policy media_private_select_member on storage.objects
  for select to authenticated
  using (
    bucket_id = 'media-private'
    and exists (
      select 1 from cms.memberships m
      where m.tenant_id::text = (storage.foldername(objects.name))[1] and m.user_id = (select auth.uid())
    )
  );

create policy media_private_insert_member on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'media-private'
    and exists (
      select 1 from cms.memberships m
      where m.tenant_id::text = (storage.foldername(objects.name))[1] and m.user_id = (select auth.uid())
    )
  );
